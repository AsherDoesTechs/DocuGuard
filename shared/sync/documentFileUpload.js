"use strict";

/**
 * The rules for uploading a file that the user picked into the cloud.
 *
 * A scanned document is already in storage: the OCR pipeline uploads it and
 * creates the server draft. A document the user picked from their device was
 * never uploaded, so the server row used to hold the metadata of the document
 * and nothing else - the file stayed on the device that picked it and was
 * unreachable from every other device and from the web app.
 *
 * The rules mirror the backend (`DocuGuard-Server/services/storageService.js`)
 * so the app can refuse a file the server would refuse anyway, instead of
 * uploading 20 MB and being told afterwards that it was not allowed.
 */

/** The formats the OCR pipeline can read, and therefore the only ones allowed. */
const ALLOWED_FILE_TYPES = [
  "application/pdf",
  "image/jpeg",
  "image/png",
  "image/webp",
  "image/heic",
  "image/heif",
];

/** The upload limit of the storage bucket. */
const MAX_FILE_BYTES = 15 * 1024 * 1024;

/**
 * Normalises a mime type the way the server does.
 *
 * @param {unknown} value
 * @returns {string}
 */
function normalizeFileType(value) {
  if (typeof value !== "string") {
    return "";
  }

  return value.toLowerCase().split(";")[0].trim();
}

/**
 * Whether a mime type is accepted by the storage service.
 *
 * @param {unknown} fileType
 * @returns {boolean}
 */
function isAllowedFileType(fileType) {
  return ALLOWED_FILE_TYPES.indexOf(normalizeFileType(fileType)) !== -1;
}

/**
 * The reason a file cannot be uploaded, or null when it can.
 *
 * @param {{ fileType?: unknown, size?: unknown }} file
 * @returns {string | null}
 */
function validateUploadFile(file) {
  const type = normalizeFileType(file && file.fileType);

  if (!type) {
    return "The file type could not be determined.";
  }

  if (!isAllowedFileType(type)) {
    return `Unsupported file type: ${type}. Allowed: ${ALLOWED_FILE_TYPES.join(", ")}`;
  }

  const size = file && file.size;

  if (typeof size === "number" && Number.isFinite(size) && size > MAX_FILE_BYTES) {
    return `The file is larger than the ${Math.round(MAX_FILE_BYTES / (1024 * 1024))} MB limit.`;
  }

  return null;
}

/**
 * Whether the document still needs its file uploaded.
 *
 * A document that already has a storage key was uploaded before, so uploading
 * it again would create a second object in the bucket for the same document.
 * A document whose file is already a remote URL is stored in the cloud.
 *
 * @param {{ s3Key?: unknown, fileUrl?: unknown }} document
 * @returns {boolean}
 */
function needsStorageUpload(document) {
  if (!document) {
    return false;
  }

  const s3Key = document.s3Key;

  if (typeof s3Key === "string" && s3Key.trim().length > 0) {
    return false;
  }

  const fileUrl = document.fileUrl;

  if (typeof fileUrl === "string" && /^https:\/\//i.test(fileUrl.trim())) {
    return false;
  }

  return true;
}

/**
 * The file name to send to the upload endpoint.
 *
 * Only the extension of the name the user picked is used. The object name in
 * the bucket is generated by the server, so the user supplied name never
 * reaches the storage path.
 *
 * @param {{ name?: unknown, fileType?: unknown }} file
 * @returns {string}
 */
function buildUploadFileName(file) {
  const type = normalizeFileType(file && file.fileType);
  const extension = type === "application/pdf" ? "pdf" : type.split("/")[1] || "jpg";
  const original = typeof (file && file.name) === "string" ? file.name : "";

  const match = original.match(/\.([a-zA-Z0-9]{1,8})$/);

  if (match) {
    return `document.${match[1].toLowerCase()}`;
  }

  return `document.${extension}`;
}

module.exports = {
  ALLOWED_FILE_TYPES,
  MAX_FILE_BYTES,
  normalizeFileType,
  isAllowedFileType,
  validateUploadFile,
  needsStorageUpload,
  buildUploadFileName,
};
